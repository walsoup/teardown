def _list_html(items: list[str], empty: str) -> str:
    if not items:
        return f"<p>{html.escape(empty)}</p>"
    rows = "".join(f"<li>{html.escape(item)}</li>" for item in items)
    return f"<ul>{rows}</ul>"


def _step_html(index: int, step: dict, image: str) -> str:
    lines = "".join(
        f'<li class="{html.escape(item["type"])}">{html.escape(item["text"])}</li>'
        for item in step_lines(step)
    )
    source = str(step.get("source") or "").strip()
    quote = f"<blockquote>&ldquo;{html.escape(source)}&rdquo;</blockquote>" if source else ""
    segmented = step.get("segmented", True)
    miss = "" if segmented else '<p class="miss">Part not highlighted. The frame is shown without an outline.</p>'
    extra = []
    if str(step.get("tool") or "").strip():
        extra.append(f"Tool: {html.escape(step['tool'])}")
    if str(step.get("fasteners") or "").strip():
        extra.append(f"Fasteners: {html.escape(step['fasteners'])}")
    if str(step.get("connectors") or "").strip():
        extra.append(f"Connectors: {html.escape(step['connectors'])}")
    meta = " &middot; ".join(extra)
    meta_html = f"<p class='when'>{meta}</p>" if meta else ""
    precaution = standard_precaution(str(step.get("part") or ""))
    precaution_html = f"<p class='precaution'>{html.escape(precaution)}</p>" if precaution else ""
    return f"""<section class="step">
<img src="{image}" alt="{html.escape(step['title'])}">
<h2><span class="n">{index}</span>{html.escape(step['title'])}</h2>
<p class="when">{html.escape(approx_clock(step.get('t') or 0))}</p>
{miss}
{quote}
<ul class="lines">{lines}</ul>
{meta_html}
{precaution_html}
</section>"""


def build_guide(plan: dict, step_images: list[str], out_path: str,
                source_attribution: str | None = None) -> str:
    steps = plan.get("steps") or []
    if len(step_images) < len(steps):
        raise ValueError("every step needs an image path")
    sections = "\n".join(
        _step_html(i + 1, step, _img64(img_path))
        for i, (step, img_path) in enumerate(zip(steps, step_images))
    )
    device = str(plan.get("device") or "device")
    article = "an" if device[:1].lower() in "aeiou" else "a"
    attribution = ""
    credit = source_attribution or plan.get("attribution") or ""
    if credit:
        attribution = "<br>Source footage: " + html.escape(str(credit))
    tools = [str(item) for item in plan.get("tools_summary") or [] if str(item).strip()]
    page = PAGE.substitute(
        title=html.escape(f"How to disassemble {article} {device}"),
        device=html.escape(device),
        count=str(len(steps)),
        tools=_list_html(tools, "No tools were named."),
        parts=_list_html(unique_parts(steps), "No parts were named."),
        steps=sections,
        attribution=attribution,
    )
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(page)
    return out_path
