def _img64(path: str) -> str:
    """Inline a step image, scaled down so a long guide stays one file."""
    try:
        import cv2

        image = cv2.imread(path)
        if image is not None and image.shape[1] > 720:
            scale = 720 / image.shape[1]
            image = cv2.resize(image, (720, max(1, int(image.shape[0] * scale))))
            ok, buf = cv2.imencode(".jpg", image, [int(cv2.IMWRITE_JPEG_QUALITY), 80])
            if ok:
                return "data:image/jpeg;base64," + base64.b64encode(buf.tobytes()).decode()
    except Exception:
        pass
    with open(path, "rb") as fh:
        return "data:image/png;base64," + base64.b64encode(fh.read()).decode()


