"""Stage 5: emit the scrollable guide page."""

from __future__ import annotations

import base64
import html


def _img64(path: str) -> str:
    with open(path, "rb") as fh:
        return "data:image/png;base64," + base64.b64encode(fh.read()).decode()


PAGE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<style>
  body {{ font-family: -apple-system, 'Segoe UI', sans-serif; background: #f4f4f6;
         color: #1c1c1e; margin: 0; }}
  main {{ max-width: 720px; margin: 0 auto; padding: 32px 16px 96px; }}
  h1 {{ font-size: 28px; }} .device {{ color: #6b6b70; margin-top: -12px; }}
  .step {{ background: #fff; border-radius: 12px; padding: 20px; margin: 24px 0;
          box-shadow: 0 1px 4px rgba(0,0,0,.12); }}
  .step img {{ width: 100%; border-radius: 8px; }}
  .step h2 {{ font-size: 18px; margin: 12px 0 4px; }}
  .step h2 .n {{ color: #fff; background: #d33; border-radius: 50%;
                display: inline-block; width: 26px; height: 26px; text-align: center;
                line-height: 26px; font-size: 15px; margin-right: 8px; }}
  .step p {{ margin: 4px 0 0; color: #3a3a3e; }}
  footer {{ color: #8e8e93; font-size: 13px; margin-top: 48px; }}
</style></head><body><main>
<h1>{title}</h1>
<p class="device">Guide for: {device} &middot; generated by teardown</p>
{steps}
<footer>Built with Muse Spark, Muse Voice Transcribe and SAM 3.1 on the Meta Model API.</footer>
</main></body></html>
"""

STEP = """<section class="step">
<img src="{img}" alt="Step {n}">
<h2><span class="n">{n}</span>{title}</h2>
<p>{instruction}</p>
</section>"""


def build_guide(plan: dict, step_images: list[str], out_path: str) -> str:
    sections = "\n".join(
        STEP.format(
            n=i + 1,
            img=_img64(img_path),
            title=html.escape(step["title"]),
            instruction=html.escape(step["instruction"]),
        )
        for i, (step, img_path) in enumerate(zip(plan["steps"], step_images))
    )
    page = PAGE.format(
        title=html.escape(f"How to disassemble a {plan['device']}"),
        device=html.escape(plan["device"]),
        steps=sections,
    )
    with open(out_path, "w") as fh:
        fh.write(page)
    return out_path
